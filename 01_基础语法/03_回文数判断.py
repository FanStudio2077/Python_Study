# 第1章 基础语法练习：取各位数字、判断回文数
# 需求：判断输入的数字是不是回文数（正着读和倒着读一样）
# 注意：现在的写法只支持 5 位数，可以用 len(str(a)) 或字符串反转来做通用版本

a = int(input("shu:"))

b = a % 10                # 个位
c = int(a / 10) % 10      # 十位
d = int(a / 100) % 10     # 百位
e = int(a / 1000) % 10    # 千位
f = int(a / 10000) % 10   # 万位

print(f"{f}")

if b == f and e == c:
    print("为回文数")
